package com.taskpilot.app.observability;

import io.opentelemetry.api.OpenTelemetry;
import io.opentelemetry.api.common.AttributeKey;
import io.opentelemetry.api.trace.StatusCode;
import io.opentelemetry.instrumentation.logback.appender.v1_0.OpenTelemetryAppender;
import io.opentelemetry.sdk.common.CompletableResultCode;
import io.opentelemetry.sdk.trace.data.SpanData;
import io.opentelemetry.sdk.trace.export.SpanExporter;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.BeansException;
import org.springframework.beans.factory.ObjectProvider;
import org.springframework.beans.factory.SmartInitializingSingleton;
import org.springframework.beans.factory.config.BeanPostProcessor;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

import java.util.Collection;
import java.util.List;

/**
 * Wires Spring Boot 4's auto-configured {@link OpenTelemetry} SDK into Logback's
 * {@link OpenTelemetryAppender} (for OTLP Logs -> Grafana Cloud Loki with trace_id correlation)
 * and filters out noisy successful {@code /actuator/**} probe/scrape spans before export to Tempo.
 */
@Slf4j
@Configuration
public class OpenTelemetryObservabilityConfig {

    private static final AttributeKey<String> ATTR_URI = AttributeKey.stringKey("uri");
    private static final AttributeKey<String> ATTR_HTTP_ROUTE = AttributeKey.stringKey("http.route");
    private static final AttributeKey<String> ATTR_URL_PATH = AttributeKey.stringKey("url.path");
    private static final AttributeKey<String> ATTR_HTTP_TARGET = AttributeKey.stringKey("http.target");

    @Bean
    public SmartInitializingSingleton openTelemetryLogbackAppenderInstaller(
            ObjectProvider<OpenTelemetry> openTelemetryProvider) {
        return () -> {
            OpenTelemetry openTelemetry = openTelemetryProvider.getIfAvailable();
            if (openTelemetry != null) {
                OpenTelemetryAppender.install(openTelemetry);
                log.info("[monitoring] OpenTelemetry Logback appender installed");
            }
        };
    }

    @Bean
    public static BeanPostProcessor actuatorNoiseSpanExporterPostProcessor() {
        return new BeanPostProcessor() {
            @Override
            public Object postProcessAfterInitialization(Object bean, String beanName) throws BeansException {
                if (bean instanceof SpanExporter exporter && !(bean instanceof ActuatorNoiseFilteringSpanExporter)) {
                    return new ActuatorNoiseFilteringSpanExporter(exporter);
                }
                return bean;
            }
        };
    }

    /**
     * Drops non-error spans generated by actuator health probes and Prometheus scrapes
     * so Grafana Cloud Tempo quota is reserved for real application/AI/LiveKit/DB traces.
     */
    static final class ActuatorNoiseFilteringSpanExporter implements SpanExporter {

        private final SpanExporter delegate;

        ActuatorNoiseFilteringSpanExporter(SpanExporter delegate) {
            this.delegate = delegate;
        }

        @Override
        public CompletableResultCode export(Collection<SpanData> spans) {
            if (spans == null || spans.isEmpty()) {
                return CompletableResultCode.ofSuccess();
            }
            List<SpanData> filtered = spans.stream()
                    .filter(span -> !isNoisyActuatorSpan(span))
                    .toList();
            if (filtered.isEmpty()) {
                return CompletableResultCode.ofSuccess();
            }
            return delegate.export(filtered);
        }

        @Override
        public CompletableResultCode flush() {
            return delegate.flush();
        }

        @Override
        public CompletableResultCode shutdown() {
            return delegate.shutdown();
        }

        static boolean isNoisyActuatorSpan(SpanData span) {
            if (span == null) {
                return true;
            }
            // Never suppress errored actuator spans so failures remain observable
            if (span.getStatus() != null && span.getStatus().getStatusCode() == StatusCode.ERROR) {
                return false;
            }
            String path = firstNonBlank(
                    span.getAttributes().get(ATTR_URI),
                    span.getAttributes().get(ATTR_HTTP_ROUTE),
                    span.getAttributes().get(ATTR_URL_PATH),
                    span.getAttributes().get(ATTR_HTTP_TARGET)
            );
            if (path != null && path.startsWith("/actuator")) {
                return true;
            }
            String name = span.getName();
            return name != null && name.contains("/actuator");
        }

        private static String firstNonBlank(String... values) {
            for (String v : values) {
                if (v != null && !v.isBlank()) {
                    return v;
                }
            }
            return null;
        }
    }
}
