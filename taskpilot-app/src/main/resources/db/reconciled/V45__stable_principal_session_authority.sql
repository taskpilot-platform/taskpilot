-- P1.2: Stable principal, durable auth session authority, epoch token_version, and bounded refresh lineage

ALTER TABLE public.users
    ADD COLUMN IF NOT EXISTS token_version BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS account_state VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    ADD COLUMN IF NOT EXISTS email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS email_verified_at TIMESTAMPTZ NULL;

UPDATE public.users
SET account_state = 'LEGACY_DISABLED'
WHERE status = 'DEACTIVATED'
  AND account_state = 'ACTIVE';

ALTER TABLE public.users
    ADD CONSTRAINT chk_users_token_version_non_negative CHECK (token_version >= 0),
    ADD CONSTRAINT chk_users_account_state CHECK (
        account_state IN ('ACTIVE', 'SELF_DEACTIVATED', 'ADMIN_SUSPENDED', 'PENDING_EMAIL', 'LEGACY_DISABLED')
    );

-- Clear pre-cutover unhashed refresh rows before switching authority to hashed session records.
DELETE FROM public.refresh_tokens;

ALTER TABLE public.refresh_tokens
    ALTER COLUMN token DROP NOT NULL,
    ADD COLUMN IF NOT EXISTS session_id UUID NOT NULL,
    ADD COLUMN IF NOT EXISTS token_hash VARCHAR(64) NOT NULL,
    ADD COLUMN IF NOT EXISTS token_version BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS revoked_at TIMESTAMPTZ NULL,
    ADD COLUMN IF NOT EXISTS revocation_reason VARCHAR(64) NULL,
    ADD COLUMN IF NOT EXISTS last_used_at TIMESTAMPTZ NULL,
    ADD CONSTRAINT chk_refresh_tokens_token_version_non_negative CHECK (token_version >= 0);

CREATE UNIQUE INDEX ux_refresh_tokens_session_id
    ON public.refresh_tokens (session_id);

CREATE UNIQUE INDEX ux_refresh_tokens_token_hash
    ON public.refresh_tokens (token_hash);

CREATE UNIQUE INDEX ux_refresh_tokens_active_user
    ON public.refresh_tokens (user_id)
    WHERE revoked_at IS NULL;

CREATE TABLE public.refresh_token_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID NOT NULL,
    user_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    consumed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_refresh_token_history_user FOREIGN KEY (user_id) REFERENCES public.users (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX ux_refresh_token_history_token_hash
    ON public.refresh_token_history (token_hash);

CREATE INDEX idx_refresh_token_history_session_id
    ON public.refresh_token_history (session_id);

CREATE INDEX idx_refresh_token_history_expires_at
    ON public.refresh_token_history (expires_at);

REVOKE ALL ON TABLE public.refresh_token_history FROM PUBLIC;
ALTER TABLE public.refresh_token_history ENABLE ROW LEVEL SECURITY;
CREATE POLICY deny_all_refresh_token_history
    ON public.refresh_token_history
    FOR ALL
    TO PUBLIC
    USING (false)
    WITH CHECK (false);
