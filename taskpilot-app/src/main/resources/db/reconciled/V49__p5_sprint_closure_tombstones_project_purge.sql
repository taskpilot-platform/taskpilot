-- P5.3: Sprint versioning, single-active-sprint partial unique index, immutable closure snapshots,
-- closure corrections, task tombstones, successor task attribution, and surviving project purge audit.

ALTER TABLE public.sprints
    ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS completed_at TIMESTAMPTZ NULL,
    ADD COLUMN IF NOT EXISTS completed_by_user_id BIGINT NULL;

ALTER TABLE public.sprints
    ADD CONSTRAINT chk_sprints_version_non_negative CHECK (version >= 0);

CREATE UNIQUE INDEX ux_sprints_one_active_per_project
    ON public.sprints (project_id)
    WHERE status = 'ACTIVE';

ALTER TABLE public.tasks
    ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMPTZ NULL,
    ADD COLUMN IF NOT EXISTS deleted_by_user_id BIGINT NULL,
    ADD COLUMN IF NOT EXISTS deletion_reason VARCHAR(255) NULL,
    ADD COLUMN IF NOT EXISTS successor_of_task_id BIGINT NULL;

ALTER TABLE public.tasks
    ADD CONSTRAINT fk_tasks_successor_of FOREIGN KEY (successor_of_task_id) REFERENCES public.tasks(id),
    ADD CONSTRAINT chk_tasks_not_self_successor CHECK (successor_of_task_id IS NULL OR successor_of_task_id <> id);

CREATE INDEX idx_tasks_project_active
    ON public.tasks (project_id, sprint_id, status)
    WHERE deleted_at IS NULL;

CREATE INDEX idx_tasks_parent_active
    ON public.tasks (parent_id)
    WHERE deleted_at IS NULL;

CREATE INDEX idx_tasks_successor_of
    ON public.tasks (successor_of_task_id)
    WHERE successor_of_task_id IS NOT NULL;

CREATE TABLE public.sprint_closure_snapshots (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sprint_id                BIGINT       NOT NULL REFERENCES public.sprints(id),
    project_id               BIGINT       NOT NULL REFERENCES public.projects(id),
    sprint_name              VARCHAR(255) NOT NULL,
    sprint_version_at_close  BIGINT       NOT NULL,
    carryover_destination    VARCHAR(32)  NOT NULL,
    target_sprint_id         BIGINT       NULL,
    total_tasks_at_close     INTEGER      NOT NULL,
    done_tasks_retained      INTEGER      NOT NULL,
    carried_over_total       INTEGER      NOT NULL,
    carried_over_todo        INTEGER      NOT NULL,
    carried_over_in_progress INTEGER      NOT NULL,
    carried_over_review      INTEGER      NOT NULL,
    snapshot_payload_json    TEXT         NOT NULL,
    closed_by_user_id        BIGINT       NOT NULL,
    closed_at                TIMESTAMPTZ  NOT NULL,
    request_id               UUID         NULL,
    CONSTRAINT ux_sprint_closure_snapshots_sprint UNIQUE (sprint_id),
    CONSTRAINT chk_sprint_closure_dest CHECK (carryover_destination IN ('BACKLOG', 'SPRINT', 'NONE')),
    CONSTRAINT chk_sprint_closure_counts_non_negative CHECK (
        total_tasks_at_close >= 0
            AND done_tasks_retained >= 0
            AND carried_over_total >= 0
            AND carried_over_todo >= 0
            AND carried_over_in_progress >= 0
            AND carried_over_review >= 0
    )
);

CREATE INDEX idx_sprint_closure_snapshots_project
    ON public.sprint_closure_snapshots (project_id, closed_at DESC);

REVOKE ALL ON TABLE public.sprint_closure_snapshots FROM PUBLIC;
ALTER TABLE public.sprint_closure_snapshots ENABLE ROW LEVEL SECURITY;
CREATE POLICY deny_all_sprint_closure_snapshots
    ON public.sprint_closure_snapshots
    FOR ALL
    TO PUBLIC
    USING (false)
    WITH CHECK (false);

CREATE TABLE public.sprint_closure_corrections (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      BIGINT      NOT NULL REFERENCES public.projects(id),
    sprint_id       BIGINT      NOT NULL REFERENCES public.sprints(id),
    task_id         BIGINT      NULL,
    correction_type VARCHAR(64) NOT NULL,
    reason          TEXT        NOT NULL,
    detail_json     TEXT        NULL,
    actor_user_id   BIGINT      NOT NULL,
    occurred_at     TIMESTAMPTZ NOT NULL,
    CONSTRAINT chk_sprint_closure_corrections_type CHECK (
        correction_type IN ('MIGRATION_CARRYOVER', 'AUDITED_CORRECTION')
    )
);

CREATE INDEX idx_sprint_closure_corrections_project_sprint
    ON public.sprint_closure_corrections (project_id, sprint_id, occurred_at DESC);

REVOKE ALL ON TABLE public.sprint_closure_corrections FROM PUBLIC;
ALTER TABLE public.sprint_closure_corrections ENABLE ROW LEVEL SECURITY;
CREATE POLICY deny_all_sprint_closure_corrections
    ON public.sprint_closure_corrections
    FOR ALL
    TO PUBLIC
    USING (false)
    WITH CHECK (false);

CREATE TABLE public.project_deletion_audits (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id                 BIGINT       NOT NULL,
    project_name               VARCHAR(255) NOT NULL,
    deleted_by_user_id         BIGINT       NOT NULL,
    request_id                 UUID         NOT NULL,
    confirmation_text          VARCHAR(255) NOT NULL,
    payload_hash               VARCHAR(64)  NOT NULL,
    deleted_counts_json        TEXT         NOT NULL,
    enqueued_cleanup_job_count INTEGER      NOT NULL DEFAULT 0,
    deleted_at                 TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ux_project_deletion_audits_project UNIQUE (project_id),
    CONSTRAINT ux_project_deletion_audits_actor_req UNIQUE (deleted_by_user_id, request_id),
    CONSTRAINT chk_project_deletion_audits_cleanup_non_negative CHECK (enqueued_cleanup_job_count >= 0)
);

REVOKE ALL ON TABLE public.project_deletion_audits FROM PUBLIC;
ALTER TABLE public.project_deletion_audits ENABLE ROW LEVEL SECURITY;
CREATE POLICY deny_all_project_deletion_audits
    ON public.project_deletion_audits
    FOR ALL
    TO PUBLIC
    USING (false)
    WITH CHECK (false);
