-- P5.1: Project timezone metadata/provenance, task optimistic/assignment versioning,
-- application-owned updated_at baseline, and durable task command idempotency.

ALTER TABLE public.projects
    ADD COLUMN IF NOT EXISTS timezone_id VARCHAR(64) NOT NULL DEFAULT 'UTC',
    ADD COLUMN IF NOT EXISTS timezone_provenance VARCHAR(64) NOT NULL DEFAULT 'LEGACY_UTC_BACKFILL';

ALTER TABLE public.projects
    ALTER COLUMN timezone_id SET DEFAULT 'Asia/Ho_Chi_Minh',
    ALTER COLUMN timezone_provenance SET DEFAULT 'PROJECT_DEFAULT';

ALTER TABLE public.projects
    ADD CONSTRAINT chk_projects_timezone_id_non_blank CHECK (btrim(timezone_id) <> ''),
    ADD CONSTRAINT chk_projects_timezone_provenance CHECK (
        timezone_provenance IN ('LEGACY_UTC_BACKFILL', 'PROJECT_DEFAULT', 'MANAGER_SELECTED')
    );

ALTER TABLE public.tasks
    ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS assignment_version BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS updated_at_legacy BOOLEAN NOT NULL DEFAULT TRUE;

UPDATE public.tasks
SET updated_at = COALESCE(updated_at, created_at, NOW())
WHERE updated_at IS NULL;

ALTER TABLE public.tasks
    ALTER COLUMN updated_at_legacy SET DEFAULT FALSE;

ALTER TABLE public.tasks
    ADD CONSTRAINT chk_tasks_version_non_negative CHECK (version >= 0),
    ADD CONSTRAINT chk_tasks_assignment_version_non_negative CHECK (assignment_version >= 0);

CREATE TABLE public.task_command_idempotency (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id  BIGINT       NOT NULL,
    operation      VARCHAR(64)  NOT NULL,
    request_id     UUID         NOT NULL,
    project_id     BIGINT       NOT NULL,
    task_id        BIGINT       NULL,
    payload_hash   VARCHAR(64)  NOT NULL,
    http_status    INTEGER      NOT NULL,
    response_json  TEXT         NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX ux_task_command_idempotency_key
    ON public.task_command_idempotency (actor_user_id, operation, request_id);

CREATE INDEX idx_task_command_idempotency_project_task
    ON public.task_command_idempotency (project_id, task_id);

REVOKE ALL ON TABLE public.task_command_idempotency FROM PUBLIC;
ALTER TABLE public.task_command_idempotency ENABLE ROW LEVEL SECURITY;
CREATE POLICY deny_all_task_command_idempotency
    ON public.task_command_idempotency
    FOR ALL
    TO PUBLIC
    USING (false)
    WITH CHECK (false);
