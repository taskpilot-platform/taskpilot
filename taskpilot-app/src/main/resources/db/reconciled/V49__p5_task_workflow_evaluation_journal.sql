    assignment_version       BIGINT      NOT NULL,
    assignment_decision_id   VARCHAR(64) NULL,
    quality_rating           INTEGER     NULL,
    evidence_status          VARCHAR(32) NOT NULL,
    rubric_version           VARCHAR(32) NOT NULL,
    accepted_submitted_at    TIMESTAMPTZ NOT NULL,
    reviewed_at              TIMESTAMPTZ NOT NULL,
    original_completed_at    TIMESTAMPTZ NOT NULL,
    commitment_due_at        TIMESTAMPTZ NULL,
    on_time                  BOOLEAN     NULL,
    timeliness_status        VARCHAR(32) NOT NULL,
    evaluation_version       INTEGER     NOT NULL,
    supersedes_evaluation_id BIGINT      NULL REFERENCES public.task_evaluations(id),
    invalidated              BOOLEAN     NOT NULL DEFAULT FALSE,
    evidence_revision        BIGINT      NOT NULL DEFAULT 1,
    created_at               TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ux_task_evaluations_sub_ver UNIQUE (submission_id, evaluation_version),
    CONSTRAINT chk_task_evaluations_version_positive CHECK (evaluation_version > 0),
    CONSTRAINT chk_task_evaluations_status CHECK (
        evidence_status IN ('INDEPENDENT_ACCEPTED', 'SELF_ATTESTED')
    ),
    CONSTRAINT chk_task_evaluations_rating CHECK (
        (evidence_status = 'INDEPENDENT_ACCEPTED' AND quality_rating BETWEEN 1 AND 5)
            OR (evidence_status = 'SELF_ATTESTED' AND quality_rating IS NULL)
    ),
    CONSTRAINT chk_task_evaluations_timeliness CHECK (
        timeliness_status IN ('ON_TIME', 'LATE', 'NO_DUE_DATE')
    )
);

