CREATE TABLE public.task_evaluations (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id                  BIGINT      NOT NULL REFERENCES public.tasks(id),
    project_id               BIGINT      NOT NULL REFERENCES public.projects(id),
    submission_id            BIGINT      NOT NULL REFERENCES public.task_submissions(id),
    review_id                BIGINT      NOT NULL REFERENCES public.task_reviews(id),
    assignee_id              BIGINT      NOT NULL,
