-- P5.2: Task submission, independent review, quality-v1 evaluation, invalidation,
-- deadline commitment revisions, immutable evidence snapshots, and durable workflow journal.

ALTER TABLE public.tasks
    ADD COLUMN IF NOT EXISTS current_submission_id BIGINT NULL,
    ADD COLUMN IF NOT EXISTS current_evaluation_id BIGINT NULL,
    ADD COLUMN IF NOT EXISTS completion_evidence_status VARCHAR(32) NULL,
    ADD COLUMN IF NOT EXISTS criteria_revision BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS due_commitment_revision BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS assignment_decision_id VARCHAR(64) NULL;

UPDATE public.tasks
SET completion_evidence_status = 'LEGACY_UNVERIFIED'
WHERE status = 'DONE'
  AND completion_evidence_status IS NULL;

ALTER TABLE public.tasks
    ADD CONSTRAINT chk_tasks_completion_evidence_status CHECK (
        completion_evidence_status IS NULL
            OR completion_evidence_status IN ('INDEPENDENT_ACCEPTED', 'SELF_ATTESTED', 'LEGACY_UNVERIFIED')
    ),
    ADD CONSTRAINT chk_tasks_criteria_revision_non_negative CHECK (criteria_revision >= 0),
    ADD CONSTRAINT chk_tasks_due_commitment_revision_non_negative CHECK (due_commitment_revision >= 0);

