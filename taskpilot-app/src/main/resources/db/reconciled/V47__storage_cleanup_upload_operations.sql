-- P4.1: Durable storage upload operations ledger and after-commit cleanup jobs.

CREATE TABLE public.storage_upload_operations (
    operation_id        UUID         PRIMARY KEY,
    owner_user_id       BIGINT       NOT NULL,
    project_id          BIGINT       NOT NULL,
    target_domain       VARCHAR(32)  NOT NULL,
    provider            VARCHAR(32)  NOT NULL,
    bucket              VARCHAR(255) NOT NULL,
    planned_object_key  VARCHAR(512) NULL,
    provider_object_key VARCHAR(512) NULL,
    original_filename   VARCHAR(255) NOT NULL,
    content_type        VARCHAR(255) NULL,
    expected_size       BIGINT       NOT NULL,
    status              VARCHAR(32)  NOT NULL DEFAULT 'RESERVED',
    attached_entity_id  BIGINT       NULL,
    lease_until         TIMESTAMPTZ  NOT NULL,
    error_code          VARCHAR(64)  NULL,
    error_message       VARCHAR(500) NULL,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_storage_upload_ops_domain CHECK (target_domain IN ('PROJECT_FILE', 'RAG_DOCUMENT')),
    CONSTRAINT chk_storage_upload_ops_provider CHECK (provider IN ('S3', 'GOOGLE_DRIVE', 'B2')),
    CONSTRAINT chk_storage_upload_ops_status CHECK (
        status IN ('RESERVED', 'PROVIDER_WRITTEN', 'ATTACHED', 'COMPENSATION_QUEUED', 'ABORTED')
    ),
    CONSTRAINT chk_storage_upload_ops_size CHECK (expected_size >= 0)
);

CREATE INDEX idx_storage_upload_ops_stale
    ON public.storage_upload_operations (status, lease_until)
    WHERE status IN ('RESERVED', 'PROVIDER_WRITTEN');

CREATE INDEX idx_storage_upload_ops_project
    ON public.storage_upload_operations (project_id);

REVOKE ALL ON TABLE public.storage_upload_operations FROM PUBLIC;
ALTER TABLE public.storage_upload_operations ENABLE ROW LEVEL SECURITY;
CREATE POLICY deny_all_storage_upload_operations
    ON public.storage_upload_operations
    FOR ALL
    TO PUBLIC
    USING (false)
    WITH CHECK (false);

CREATE TABLE public.storage_cleanup_jobs (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dedupe_key          VARCHAR(64)  NOT NULL,
    provider            VARCHAR(32)  NOT NULL,
    bucket              VARCHAR(255) NOT NULL,
    object_key          VARCHAR(512) NOT NULL,
    operation           VARCHAR(32)  NOT NULL DEFAULT 'DELETE_OBJECT',
    source_type         VARCHAR(64)  NOT NULL,
    source_id           VARCHAR(128) NULL,
    project_id          BIGINT       NULL,
    upload_operation_id UUID         NULL,
    status              VARCHAR(32)  NOT NULL DEFAULT 'PENDING',
    attempts            INTEGER      NOT NULL DEFAULT 0,
    max_attempts        INTEGER      NOT NULL DEFAULT 6,
    next_attempt_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    lease_owner         VARCHAR(128) NULL,
    lease_until         TIMESTAMPTZ  NULL,
    last_error_code     VARCHAR(64)  NULL,
    last_error_message  VARCHAR(500) NULL,
    completed_at        TIMESTAMPTZ  NULL,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_storage_cleanup_jobs_provider CHECK (provider IN ('S3', 'GOOGLE_DRIVE', 'B2')),
    CONSTRAINT chk_storage_cleanup_jobs_operation CHECK (operation IN ('DELETE_OBJECT')),
    CONSTRAINT chk_storage_cleanup_jobs_status CHECK (status IN ('PENDING', 'IN_PROGRESS', 'SUCCEEDED', 'DEAD_LETTER')),
    CONSTRAINT chk_storage_cleanup_jobs_attempts CHECK (attempts >= 0 AND max_attempts > 0)
);

CREATE UNIQUE INDEX ux_storage_cleanup_jobs_active_dedupe
    ON public.storage_cleanup_jobs (dedupe_key)
    WHERE status IN ('PENDING', 'IN_PROGRESS');

CREATE INDEX idx_storage_cleanup_jobs_claim
    ON public.storage_cleanup_jobs (status, next_attempt_at, lease_until, id)
    WHERE status IN ('PENDING', 'IN_PROGRESS');

CREATE INDEX idx_storage_cleanup_jobs_project_id
    ON public.storage_cleanup_jobs (project_id);

REVOKE ALL ON TABLE public.storage_cleanup_jobs FROM PUBLIC;
ALTER TABLE public.storage_cleanup_jobs ENABLE ROW LEVEL SECURITY;
CREATE POLICY deny_all_storage_cleanup_jobs
    ON public.storage_cleanup_jobs
    FOR ALL
    TO PUBLIC
    USING (false)
    WITH CHECK (false);
